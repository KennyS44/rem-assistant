"""Диктовка — сама работа в assistant.Assistant.dictate (ей нужен микрофон)."""
from .base import skill


@skill("dictation", "Диктовка",
       "Печатать сказанное туда, где курсор, пока не скажут «хватит».",
       examples=["записывай", "диктовка", "режим диктовки", "начни диктовку", "начать диктовку",
                 "пиши под диктовку", "печатай под диктовку", "печатай за мной", "записывай за мной",
                 "диктую", "я диктую", "под диктовку", "включи диктовку", "давай диктовку", "пиши за мной"],
       category="Окна", model=False)
def dictation(ctx):
    # быстрым путём, без модели: её список умений и так почти упирается в окно 4096 токенов,
    # а «напиши привет в поле» — это type_text, путать их ей незачем
    return ctx.dictate()
