def phrases() -> list[str]:
    """Всё, что озвучивается заранее. Меняешь список — пересобери клипы (voice/design.py pack)."""
    from .reminders import due_phrase, say_when
    from .skills import REGISTRY
    from .text import duration_ru, elapsed_ru
    out = ["Рэм слушает.", "Рэм всё сделала.", "Простите, Рэм не расслышала.", "Хорошо, Рэм не будет.",
           "Таймеры отменены.", "Таймеров нет.", "На сколько поставить таймер?"]
    for m in TIMER_MINUTES:
        label = duration_ru(m * 60)
        out += [f"Таймер на {label}.", f"{elapsed_ru(m * 60)} — таймер закончился."]
    for s in sorted(REGISTRY.values(), key=lambda s: s.name):
        if s.confirm and not s.retell:           # «любая команда» спрашивает своими словами — их не записать
            out.append(f"{s.title}? Скажите «да» или «нет».")
    out += FIXED
    evening = dt.datetime(2026, 1, 1, 22, 0)
    for h, m in ALARM_TIMES:
        at = dt.datetime(2026, 1, 2, h, m)
        out += [f"Рэм разбудит вас {say_when(at, evening)}.",
                due_phrase({"kind": "alarm", "at": at.isoformat()}, rem=True)]
    return out


def key(text: str) -> str:
    norm = " ".join(text.lower().replace("ё", "е").split())
    return hashlib.sha1(norm.encode("utf-8")).hexdigest()[:12]


def clip(text: str) -> Path | None:
    p = CLIPS / f"{key(text)}.wav"
    return p if p.exists() else None


def clips_for(text: str) -> list[Path] | None:
    """Клипы, покрывающие весь ответ, — или None, если хоть куска нет
    (тогда весь ответ говорит нейроголос: смена голоса посреди фразы режет слух).
    Записаны и целые фразы из нескольких предложений («Выключить компьютер? Скажите «да» или «нет».»),
    и отдельные — берём самый длинный записанный кусок подряд."""
    parts = [p for p in re.split(r"(?<=[.!?])\s+", text.strip()) if p]
    found, i = [], 0
    while i < len(parts):
        for j in range(len(parts), i, -1):
            c = clip(" ".join(parts[i:j]))
            if c:
                found.append(c)
                i = j
                break
        else:
            return None
    return found or None
